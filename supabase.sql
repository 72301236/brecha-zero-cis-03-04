-- Execute no SQL Editor do Supabase.
create table if not exists public.quiz_results (
  id bigint generated by default as identity primary key,
  player_name text not null,
  score integer not null default 0,
  correct_count integer not null default 0,
  duration_ms bigint not null default 0,
  answers jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.quiz_results enable row level security;
alter table public.quiz_results drop constraint if exists quiz_results_player_name_check;
alter table public.quiz_results drop constraint if exists quiz_results_score_check;
alter table public.quiz_results drop constraint if exists quiz_results_correct_count_check;
alter table public.quiz_results add constraint quiz_results_player_name_check check (char_length(player_name) between 1 and 30);
alter table public.quiz_results add constraint quiz_results_score_check check (score between 0 and 2000);
alter table public.quiz_results add constraint quiz_results_correct_count_check check (correct_count between 0 and 20);

drop policy if exists "quiz_results_insert_demo" on public.quiz_results;
create policy "quiz_results_insert_demo" on public.quiz_results for insert to anon
with check (char_length(player_name) between 1 and 30 and score between 0 and 2000 and correct_count between 0 and 20);
drop policy if exists "quiz_results_read_demo" on public.quiz_results;
create policy "quiz_results_read_demo" on public.quiz_results for select to anon using (true);
grant usage on schema public to anon;
grant select, insert on public.quiz_results to anon;
grant usage, select on sequence public.quiz_results_id_seq to anon;
